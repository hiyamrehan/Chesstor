"""Generate app/src/overlay/fixtures/geometry.json: reference square positions computed with OpenCV.

The TypeScript projection (app/src/overlay/projection.ts) must reproduce these pixels
(see projection.test.ts), so the two implementations are checked against each other.
Re-run after changing the contract:
    python scripts/gen_overlay_fixture.py
tests/test_overlay_geometry.py fails if the committed fixture is stale.
"""
import json
import sys
from pathlib import Path

import cv2
import numpy as np

from chesstor.vision.synth import random_view, render_board

OUT = Path(__file__).resolve().parents[1] / "app/src/overlay/fixtures/geometry.json"
FILES = "abcdefgh"


def content_rect(cw, ch, vw, vh):
    va = vw / vh
    if cw / ch > va:
        w = ch * va
        return {"x": (cw - w) / 2, "y": 0.0, "w": w, "h": float(ch)}
    h = cw / va
    return {"x": 0.0, "y": (ch - h) / 2, "w": float(cw), "h": h}


def build() -> dict:
    import chess
    view, c = random_view(render_board(chess.Board(), seed=1), seed=3)
    h, w = view.shape[:2]
    base = (c / [w, h]).tolist()        # a8, h8, h1, a1 as a camera sees them with white at the bottom
    corner_sets = {
        "white-at-bottom": base,
        "white-at-top-180": [[1 - x, 1 - y] for x, y in base],
        "phone-sideways-90cw": [[1 - y, x] for x, y in base],
    }
    boxes = {"tall-400x700": (400, 700), "wide-960x540": (960, 540)}
    media = {"w": 1280, "h": 960}
    cases = []
    for cname, corners in corner_sets.items():
        for bname, (bw, bh) in boxes.items():
            rect = content_rect(bw, bh, media["w"], media["h"])
            px = np.array([[rect["x"] + x * rect["w"], rect["y"] + y * rect["h"]] for x, y in corners],
                          np.float32)
            plane = np.array([[0, 0], [8, 0], [8, 8], [0, 8]], np.float32)
            H = cv2.getPerspectiveTransform(plane, px)

            def proj(bx, by, H=H):
                x, y = cv2.perspectiveTransform(np.array([[[bx, by]]], np.float32), H)[0, 0]
                return [round(float(x), 3), round(float(y), 3)]

            centres, polys = {}, {}
            for i in range(64):
                f, r = i % 8, i // 8
                sq = FILES[f] + str(r + 1)
                ox, oy = f, 7 - r                                  # board plane: y = 8 - rank
                centres[sq] = proj(ox + 0.5, oy + 0.5)
                if sq in ("a1", "h1", "a8", "h8", "e4"):
                    polys[sq] = [proj(ox, oy), proj(ox + 1, oy), proj(ox + 1, oy + 1), proj(ox, oy + 1)]
            cases.append({"name": f"{cname}/{bname}", "corners": corners, "media": media,
                          "box": {"w": bw, "h": bh}, "centres": centres, "polygons": polys,
                          "rect": {k: round(v, 3) for k, v in rect.items()}})
    return {"note": "generated by scripts/gen_overlay_fixture.py (OpenCV reference); do not edit by hand",
            "cases": cases}


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(build(), indent=1) + "\n")
    print("wrote", OUT, file=sys.stderr)
